/**
 * Illustration: booking a time slot without double booking.
 *
 * Written for this case study, not copied from the product. Each booking reads
 * two lock docs inside one transaction: one for the member, one for the slot.
 * If another booking writes either of them first, Firestore retries this
 * transaction, which then sees the slot taken and stops.
 */

const slotKey = (start) => start.toISOString().slice(0, 16).replace(/[-:T]/g, ""); // "202610121130"

class BookingError extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

/**
 * @param {FirebaseFirestore.Firestore} db
 * @param {{ requestId: string, userId: string, start: Date, allowance: number }} booking
 *   requestId is generated by the client once per attempt and becomes the
 *   ticket id, so a retried request finds its own ticket instead of making a
 *   second one.
 */
async function bookSlot(db, { requestId, userId, start, allowance }) {
  const memberLock = db.collection("memberLocks").doc(userId);
  const slotLock = db.collection("slotLocks").doc(slotKey(start));
  const ticket = db.collection("tickets").doc(requestId);

  return db.runTransaction(async (tx) => {
    // All reads before any write, as Firestore transactions require.
    const [, slot, existing, used] = await Promise.all([
      tx.get(memberLock), // read so concurrent bookings by one member serialise
      tx.get(slotLock),
      tx.get(ticket),
      tx.get(db.collection("tickets").where("userId", "==", userId)),
    ]);

    if (existing.exists) return existing.data(); // retry of the same request
    if (slot.exists) throw new BookingError("SLOT_TAKEN", "That time was just booked.");
    if (used.size >= allowance) throw new BookingError("NO_ALLOWANCE", "No sessions left this year.");

    const data = { userId, start, status: "booked", createdAt: new Date() };
    tx.set(ticket, data);
    tx.set(slotLock, { ticket: requestId, userId });
    tx.set(memberLock, { lastBookingAt: new Date() }, { merge: true });
    return data;
  });
}

module.exports = { bookSlot, slotKey, BookingError };
